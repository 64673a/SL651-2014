def get_guide_name(guide: int, func_code: int | None = None) -> str:
    """根据引导符和功能码返回要素/参数名称。

    要素标识符与配置参数标识符取值重叠（见表26注），由功能码区分：
    - 40H/41H → 基本配置表（附录D.1）
    - 42H/43H → 运行参数配置表（附录D.4）
    - 其他 → 常规要素（附录C）
    """
    if func_code is not None:
        if func_code in BASIC_CONFIG_FUNC_CODES:
            name = BASIC_CONFIG_GUIDES.get(guide)
            if name:
                return name
        elif func_code in RUN_PARAM_FUNC_CODES:
            name = RUN_PARAM_GUIDES.get(guide)
            if name:
                return name
    entry = ELEMENT_GUIDES.get(guide)
    if entry:
        return entry[1]
    return f"未知要素({guide:02X})"
